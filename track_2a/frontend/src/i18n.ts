export type UiTexts = (typeof texts)["de"];

function uiLanguage(lang: LanguageCode): UiLanguage {
  return lang === "gsw" ? "de" : lang;
}

/** All UI texts for the chosen interview language. */
export function t(lang: LanguageCode): UiTexts {
  return texts[uiLanguage(lang)];
}

/** Pick the right text from a backend label like { de: "...", fr: "..." }. */
export function label(l: LocalizedLabel, lang: LanguageCode): string {
  return l[lang] ?? l[uiLanguage(lang)] ?? l.de ?? Object.values(l)[0] ?? "";
}
